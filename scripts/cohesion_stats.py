# -*- coding: utf-8 -*-
"""句间逻辑连接的测量——查「每句都像 bullet point」。

用法：
  python3 scripts/cohesion_stats.py <语料目录> <稿件.md> [更多稿件…]

三个指标，全部按「整句」（到。？！）计：
  ① 句首连接词占比：句首 8 字内出现因果/转折/条件/递进/解释/让步类连接词的句子比例
  ② 句内因果链占比：句中含 因为/由于/所以/因此/从而/既然/之所以/则/便/就/于是 等的句子比例
     （单字 则/才/便/就 不算「规则」「人才」「便利」「成就」这类实词里的，介词「就」（就本案而言）
     也不算，见 INNER 注释）
  ③ 段首承接上段占比：段首句以连接词或回指词（这/此/该/上述/前述/前例/同理…）起头的段落比例

2026-09 实测（Q1/中位/Q3；只取正文段 ≥15 且汉字 ≥3000 的篇目，已删去重复文件和三份立法建议稿）：
  民法所 363 篇
    ① 17.1 / 21.8 / 27.2　（其中因果 7.5、转折 4.7、条件 3.3）
    ② 23.3 / 28.5 / 34.2
    ③ 11.8 / 17.9 / 25.4
  国际法学院国经、国公、国私三所 332 篇
    ① 16.0 / 20.8 / 25.5　（其中因果 6.0、转折 3.7、条件 1.5）
    ② 16.9 / 21.6 / 27.3
    ③  8.1 / 14.4 / 21.1
  这是修正 HEAD、INNER 之后的数。修正前（民法所当时含重复文件，386 篇）的 ② 是
  民法 30.2 / 36.3 / 43.4、国际法 26.6 / 33.0 / 39.4；两套不可混比，旧口径下的稿件 P 值要按新口径重算。
一份 AI 协作稿：① 4.3%（低于全部 363 篇），转折 0.3%（P1）——每二十多句才有一句交代自己与上一句的关系。
见 SKILL.md 第五节之二。
"""
import re, sys, os, glob, bisect, statistics as st
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mineru_body import body_paras

# 句首的单字、多义连接词同样要挡实词语素（2026-09 补）：事故、故意、故宫里的「故」，但书里的「但」，
# 阻却、除却里的「却」，若干里的「若」，同时履行里的「同时」。「不但」是递进，从转折挪过去；
# 「只是」前面有字时多是"仅仅"（这只是、它只是），只算句首或标点后的。
HEAD = {
 '因果': r'(因此|因而|所以|故而|是故|于是|由此|可见|据此|从而|正因|既然|由于|因为|这样一来|如此一来|结果是|(?<![事缘变无典已世何])故(?![意宫障乡居]))',
 '转折': r'((?<!不)(?:但是|但(?!书))|然而|不过|可是|反之|相反|(?<![阻除冷推退忘了])却|(?<![一-鿿])只是)',
 '条件': r'(如果|倘若|假如|若(?!干)|一旦|只有|只要|否则|除非|无论|不论)',
 '递进': r'(而且|并且|况且|何况|甚至|进而|更何况|不仅|不但|此外|另外|同时(?!履行)|再者)',
 '解释': r'(换言之|也就是说|亦即|具体而言|具体来说|例如|比如|譬如|质言之|事实上|实际上)',
 '让步': r'(虽然|尽管|即便|即使|固然|纵然)',
}
# 单字的 则/才/便/就 同时是别的词的语素，必须排除（2026-09 修）。旧式 `…|才|否则|则|便|就|…`
# 把「规则」「原则」「人才」「便利」「成就」都算成因果标记，法学论文「规则」「原则」极多，
# ② 的语料中位因此虚高 7–10 个百分点（清理后的民法 37.2 → 29.8，国际法 33.0 → 23.0）；
# 介词「就」再虚高 1.3–1.4 个点（→ 28.5、21.6）。
# 环视只挡实词语素，逐条回语料核过；下列「放回」的都是实测里的真连词：
#   则：规则 原则 细则 准则 总则 分则 附则 守则 通则 罚则 实则。「部分则」「处分则」「标准则」
#       「事实则」「遵守则」放回；「章则」不挡——语料 8 处全是「第三章则规定」「行政规章则有」。
#       「法则」约三成是「英美法则是」「德国法则将」「方法则是」，所以只在后接标点、的、之、
#       区（法则区别说）、说（权衡法则说）时挡。
#   才：人才。但「当事人才能」「自然人才享有」「债务人才有义务」是条件句，后接能可享承得会有时放回。
#   便：便利 方便 便捷。「行为人便利用」「以便利益关系人」「对方便可」放回。
#   就：成就（含民法的「条件成就」）、就业；「一旦形成就」「完成就」放回。
#       介词「就」是"关于"，也不算：句首的就（就本案而言，…）、「就…而言/来说/而论/来看」、
#       就其、就上述/同一/相关/合同/法律/当事人/《…》……；「就此」只在后接结束、成立、消亡这类
#       表"由此"的动词时照计。比较义的「就如」「就像」也不算。「如果……就……」「一……就……」照计。
_JIU_NOT = '|'.join([
    '业', '其', '如', '像', '好像', '好比',
    '本案', '该案', '此案', '上述', '前述', '这一', '这些', '此类', '同一', '相关', '具体', '个别', '某一', '某些',
    '当事人', '合同', '法律', '法院', '争议', '争端', '《',
    '此(?!结束|成为|失去|画上|成立|消亡|消灭|初现|开始|变成|止步|终结|终止|中止|告终|完结|平息|洞开|取代|免责|生效|丧失|打住|停止|被)',
    '(?![可能会应要没已都也只必须需将被使让便])[^，,。；：？！]{1,30}?(?:而言|来说|而论|来看)',
])
INNER = '(' + '|'.join([
    '因为', '由于', '所以', '因此', '因而', '从而', '以致', '既然', '之所以', '否则', '于是',
    r'(?<![规原细准法总分附守通罚实否])则', r'(?<=部分|处分|标准|事实|遵守)则',
    r'(?<=法)则(?![区的之说，,。、；：“”…—（）()《》])',
    r'(?<!人)才', r'(?<=人)才(?=[能可享承得会有])',
    r'(?<!方)便(?!利(?![用益])|捷)', r'(?<=[对双一各买卖]方)便(?!利|捷)',
    r'(?<=.)(?:(?<!成)|(?<=形成|完成))就(?!' + _JIU_NOT + ')',     # (?<=.)：句首的就不算，见 inner_hit
]) + ')'
BACKREF = r'(这|此|该|上述|前述|如前|据此|前文|前例|同理|同样|与此)'

def sents(t):
    return [s for s in re.split(r'(?<=[。？！])', t) if len(re.findall(r'[一-鿿]', s)) > 4]

def _head(s, n=8):
    return re.sub(r'^[“”"（(〔\s]*', '', s)[:n]

def inner_hit(s):
    """② 的判定。先剥掉句首的引号、括号、空格，INNER 里的 (?<=.) 才认得出句首的介词「就」。"""
    return re.search(INNER, _head(s, None))

def analyse(paras):
    S = [s for p in paras for s in sents(p)]
    n = len(S) or 1
    cnt = {k: 0 for k in HEAD}; anyhead = inner = 0
    for s in S:
        h = _head(s)
        for k, pat in HEAD.items():
            if re.match(r'^.{0,3}' + pat, h):
                cnt[k] += 1; anyhead += 1; break
        if inner_hit(s): inner += 1
    link = 0
    for p in paras[1:]:
        ss = sents(p)
        if ss and re.match(r'^.{0,3}(' + '|'.join(HEAD.values()) + '|' + BACKREF + ')', _head(ss[0], 10)):
            link += 1
    r = dict(n=n, head=anyhead/n*100, inner=inner/n*100, plink=link/max(len(paras)-1, 1)*100)
    r.update({k: v/n*100 for k, v in cnt.items()})
    return r

def draft_paras(path):
    t = open(path, encoding='utf-8').read()
    i = t.find('## 一、')
    t = t[i:] if i >= 0 else t
    t = t.split('<!-- 以下')[0]
    return [p.strip() for p in t.split('\n\n')
            if p.strip() and not p.lstrip().startswith(('#', '|', '表', '**', '[^'))]

ROWS = [('head', '① 句首有连接词 %'), ('因果', '   其中因果 %'), ('转折', '   其中转折 %'),
        ('条件', '   其中条件 %'), ('inner', '② 句内有因果链 %'), ('plink', '③ 段首承接上段 %')]

def main():
    if len(sys.argv) < 3:
        print(__doc__); sys.exit(1)
    root, drafts = sys.argv[1], sys.argv[2:]
    R = []
    for f in sorted(glob.glob(os.path.join(root, '**', '*.md'), recursive=True)):
        ps = body_paras(f)
        if len(ps) < 15 or len(re.findall(r'[一-鿿]', ''.join(ps))) < 3000: continue
        R.append(analyse(ps))
    if not R:
        sys.exit(f'语料目录里没有可用的 md（正文段 ≥15 且汉字 ≥3000 的 MinerU 解析稿）：{root}')
    print(f'语料 {len(R)} 篇（Q1 / 中位 / Q3）')
    for k, nm in ROWS:
        v = sorted(r[k] for r in R); m = len(v)
        print(f'  {nm:18} {v[m//4]:5.1f} / {st.median(v):5.1f} / {v[3*m//4]:5.1f}')
    for d in drafts:
        r = analyse(draft_paras(d))
        print(f'\n{os.path.basename(d)}（{r["n"]} 句）')
        for k, nm in ROWS:
            v = sorted(x[k] for x in R); pct = bisect.bisect(v, r[k]) / len(v) * 100
            flag = '  ⚠<Q1' if r[k] < v[len(v)//4] else ''
            print(f'  {nm:18} {r[k]:5.1f}   P{pct:.0f}{flag}')

if __name__ == '__main__':
    main()
